def render_markdown(content: str, sty: dict) -> list:
    """Render the small, intentionally portable report Markdown vocabulary."""
    lines = content.splitlines()
    blocks = []
    i = 0
    while i < len(lines):
        line = lines[i].strip()
        if not line:
            i += 1
            continue
        if line == "<!-- pagebreak -->":
            blocks.append(PageBreak())
            i += 1
        elif line.startswith("# "):
            blocks.append(Paragraph(inline(line[2:]), sty["h1"]))
            i += 1
        elif line.startswith("## "):
            blocks.append(Paragraph(inline(line[3:]), sty["h2"]))
            i += 1
        elif line.startswith("!["):
            match = re.fullmatch(r"!\[(.*)\]\((.*)\)", line)
            if not match:
                raise ValueError("Malformed report figure")
            caption, target = match.groups()
            path = (REPORT / target).resolve()
            image = Image(str(path))
            max_height = 226 if "rise_time" in target else 256
            if "part1_summary" in target:
                max_height = 375
            if "reflection_comparison" in target:
                max_height = 340
            if "alpha_comparison" in target:
                max_height = 290
            ratio = min(BODY_WIDTH / image.imageWidth, max_height / image.imageHeight)
            image.drawWidth, image.drawHeight = image.imageWidth * ratio, image.imageHeight * ratio
            image.hAlign = "CENTER"
            blocks.append(KeepTogether([image, Paragraph(inline(caption), sty["caption"])]))
            i += 1
        elif line.startswith("```"):
            kind = line[3:]
            values = []
            i += 1
            while i < len(lines) and not lines[i].startswith("```"):
                values.append(lines[i])
                i += 1
            i += 1
            blocks.append(Preformatted("\n".join(values), sty["equation"], maxLineLength=88))
        elif line.startswith("|"):
            values = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                cells = [v.strip() for v in lines[i].strip().strip("|").split("|")]
                if not all(re.fullmatch(r":?-+:?", c.replace(" ", "")) for c in cells):
                    row_style = sty["tablehead"] if not values else sty["table"]
                    values.append([Paragraph(inline(c), row_style) for c in cells])
                i += 1
            count = len(values[0])
            if count == 2:
                widths = [BODY_WIDTH * 0.43, BODY_WIDTH * 0.57]
            else:
                widths = [BODY_WIDTH * 0.52] + [BODY_WIDTH * 0.48 / (count - 1)] * (count - 1)
                if "alpha" in values[0][0].getPlainText():
                    widths = [BODY_WIDTH * .15, BODY_WIDTH * .40, BODY_WIDTH * .45]
            table = Table(values, colWidths=widths, repeatRows=1, hAlign="LEFT")
            table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), NAVY),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, PALE]),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 7),
                ("RIGHTPADDING", (0, 0), (-1, -1), 7),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("LINEBELOW", (0, -1), (-1, -1), .4, colors.HexColor("#D5DFE5")),
            ]))
            blocks.extend([table, Spacer(1, 10)])
        else:
            values = [line]
            i += 1
            while i < len(lines) and lines[i].strip() and not lines[i].startswith(("#", "![", "```", "|", "<!--")):
                if re.match(r"\d+\. ", lines[i].strip()):
                    break
                values.append(lines[i].strip())
                i += 1
            blocks.append(Paragraph(inline(" ".join(values)), sty["body"]))
    return blocks


def source_appendix(path: Path, title: str, sty: dict, new_page: bool = True) -> list:
    blocks = [Paragraph(title, sty["h1"]),
              Paragraph(f"Complete source: {path.relative_to(ROOT).as_posix()}. "
                        "Line numbers mark original source lines; continued display lines are indented.", sty["caption"])]
    formatted = []
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        expanded = line.expandtabs(4)
        # Explicit display wrapping keeps long source lines inside the margin.
        pieces = textwrap.wrap(expanded, width=88, expand_tabs=False,
                               replace_whitespace=False, drop_whitespace=False,
                               break_long_words=True, break_on_hyphens=False) or [""]
        formatted.append(f"{number:4d}  {pieces[0]}")
        formatted.extend("      " + p for p in pieces[1:])
    # Splittable Preformatted keeps the full executable source legible.
    blocks.append(Preformatted("\n".join(formatted), sty["code"]))
    return [PageBreak()] + blocks if new_page else [Spacer(1, 20), KeepTogether(blocks)]


